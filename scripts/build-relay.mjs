// Bundles the relay launcher (TypeScript) into runnable relay.mjs.
import esbuild from "esbuild";

await esbuild.build({
	entryPoints: ["src/sync/relayLauncher.ts"],
	bundle: true,
	platform: "node",
	format: "esm",
	target: "node20",
	// ws is CJS and dynamically requires node builtins — must stay external.
	external: ["ws"],
	outfile: "relay.mjs",
	banner: {
		js: "// Generated by scripts/build-relay.mjs — do not edit; edit src/sync/relayLauncher.ts",
	},
	logLevel: "info",
});
console.log("relay.mjs built");
